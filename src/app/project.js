// Astra Editor · acceso al proyecto de RPG Maker MZ.
// Un "backend" sabe leer y escribir archivos por ruta relativa ("data/Map001.json").
//   FolderBackend: carpeta elegida con el selector de Chrome/Edge (File System Access API).
//   HttpBackend:   lectura por HTTP y escritura en memoria (demo y pruebas automáticas).
"use strict";
const Astra=window.Astra=window.Astra||{};

class FolderBackend{
 constructor(dir){this.dir=dir;this.name=dir.name;}
 async handle(path,create){const parts=path.split("/").filter(Boolean);let d=this.dir;
  for(const p of parts.slice(0,-1))d=await d.getDirectoryHandle(p,{create:!!create});
  return d.getFileHandle(parts[parts.length-1],{create:!!create});}
 async exists(path){try{await this.handle(path);return true;}catch(e){return false;}}
 async blob(path){return (await this.handle(path)).getFile();}
 async text(path){return (await this.blob(path)).text();}
 async write(path,text){const w=await (await this.handle(path,true)).createWritable();await w.write(text);await w.close();}
 async removeMap(path){if(!/^data\/Map[0-9]+\.json$/.test(path))throw new Error("Ruta de mapa no válida");const data=await this.dir.getDirectoryHandle("data");await data.removeEntry(path.slice(5));}
 async permission(){const o={mode:"readwrite"};if(await this.dir.queryPermission(o)==="granted")return true;return (await this.dir.requestPermission(o))==="granted";}
}
class HttpBackend{
 constructor(base,name){this.base=base.replace(/\/?$/,"/");this.name=name||"Demo";this.writes={};}
 url(path){return this.base+path.split("/").map(encodeURIComponent).join("/");}
 async exists(path){if(path in this.writes)return true;try{return (await fetch(this.url(path),{method:"HEAD"})).ok;}catch(e){return false;}}
 async blob(path){if(path in this.writes)return new Blob([this.writes[path]]);const r=await fetch(this.url(path));if(!r.ok)throw new Error("No existe "+path);return r.blob();}
 async text(path){return (await this.blob(path)).text();}
 async write(path,text){this.writes[path]=text;}
}
Astra.FolderBackend=FolderBackend;Astra.HttpBackend=HttpBackend;

// ---------- plugins.js ----------
const OLD_PLUGINS=["TacticsSystem","TacticsCommands","TacticsRules","TacticsView","TacticsGraphics","TacticsPresentation","TacticsScenes","TacticsData"];
Astra.parsePlugins=function(text){const start=text.indexOf("["),end=text.lastIndexOf("]");if(start<0||end<start)return [];return JSON.parse(text.slice(start,end+1));};
Astra.writePlugins=list=>"// Generated by RPG Maker.\n// Do not edit this file directly.\nvar $plugins =\n[\n"+list.map(p=>JSON.stringify(p)).join(",\n")+"\n];\n";
// Estado de la instalación de TacticsMZ en el proyecto.
Astra.pluginStatus=function(list){
 const on=n=>list.some(p=>p.name===n&&p.status);
 const old=OLD_PLUGINS.filter(on),hasNew=on("TacticsEngine")&&on("TacticsUI"),mz=on("TacticsMZ");
 return {old,hasNew,mz,ok:mz&&hasNew&&!old.length,legacy:mz&&old.length>0,missing:!mz};
};
// Sustituye los 9 plugins de la v0.2 por los 3 de la v0.3, conservando los parámetros de TacticsMZ.
Astra.upgradePlugins=function(list){
 const out=list.filter(p=>OLD_PLUGINS.indexOf(p.name)<0&&p.name!=="TacticsEngine"&&p.name!=="TacticsUI");
 let at=out.findIndex(p=>p.name==="TacticsMZ");
 if(at<0){out.push({name:"TacticsMZ",status:true,description:"TacticsMZ",parameters:{}});at=out.length-1;}
 out[at]=Object.assign({},out[at],{status:true,parameters:Object.assign({EnemyPresets:"[]"},out[at].parameters)});
 out.splice(at,0,{name:"TacticsEngine",status:true,description:"TacticsMZ · núcleo",parameters:{}},{name:"TacticsUI",status:true,description:"TacticsMZ · interfaz",parameters:{}});
 return out;
};

// ---------- carga del proyecto ----------
const json=async(b,path,optional)=>{try{return JSON.parse(await b.text(path));}catch(e){if(optional)return null;throw new Error("No pude leer "+path+": "+e.message);}};
Astra.loadProject=async function(backend){
 if(!await backend.exists("data/System.json"))throw new Error("Esta carpeta no parece un proyecto de RPG Maker MZ: falta data/System.json. Elige la carpeta que contiene game.rmmzproject.");
 const p={backend,name:backend.name,images:{},warnings:[]};
 const files={system:"System",mapInfos:"MapInfos",tilesets:"Tilesets",classes:"Classes",actors:"Actors",weapons:"Weapons",items:"Items",skills:"Skills",states:"States"};
 await Promise.all(Object.keys(files).map(async k=>{p[k]=await json(backend,"data/"+files[k]+".json");}));
 p.title=(p.system&&p.system.gameTitle)||backend.name;
 p.tileSize=(p.system&&p.system.tileSize)||48;
 p.plugins=await backend.exists("js/plugins.js")?Astra.parsePlugins(await backend.text("js/plugins.js")):[];
 p.pluginStatus=Astra.pluginStatus(p.plugins);
 const mz=p.plugins.find(x=>x.name==="TacticsMZ")||{parameters:{}};
 p.tacticsParams=mz.parameters||{};
 Tactics.setEnemyPresets(Tactics.decode(p.tacticsParams.EnemyPresets||"[]")||[]);
 // Paquete de gráficos (opcional): terrenos con nombre, imagen de cada mapa y sprites de clase.
 const pack=String(p.tacticsParams.ResourcePack||"");
 p.packName=pack||null;
 p.pack=pack&&/^[a-zA-Z0-9_/-]+$/.test(pack)?await json(backend,"data/"+pack+".json",true):null;
 p.terrain=(p.pack&&p.pack.terrain)||Tactics.copy(Tactics.exampleDatabase.terrain);
 // Tablas de autotiles: se leen del propio rmmz_core.js del proyecto.
 p.autotiles=null;
 try{const core=await backend.text("js/rmmz_core.js"),t={};
  ["FLOOR","WALL","WATERFALL"].forEach(k=>{const m=core.match(new RegExp("Tilemap\\."+k+"_AUTOTILE_TABLE\\s*=\\s*(\\[[\\s\\S]*?\\]);"));if(m)t[k]=JSON.parse(m[1]);});
  if(t.FLOOR&&t.WALL&&t.WATERFALL)p.autotiles=t;
 }catch(e){}
 if(!p.autotiles)p.warnings.push("No encontré js/rmmz_core.js: los autotiles (agua, hierba…) se verán como color plano.");
 Astra.refreshDatabase(p);
 return p;
};
// Base de datos táctica (la misma que usa el juego), para revisar misiones y calcular alcances.
Astra.refreshDatabase=function(p){
 p.db=Tactics.readDatabase({classes:p.classes,actors:p.actors,weapons:p.weapons,items:p.items,skills:p.skills,states:p.states});
 p.db.tilesets=p.tilesets;p.db.terrain=Tactics.copy(p.terrain);if(p.pack)p.db.graphics=p.pack;
};
Astra.mapPath=id=>"data/Map"+String(id).padStart(3,"0")+".json";
Astra.loadMap=async(p,id)=>json(p.backend,Astra.mapPath(id));
// Guarda con copia de seguridad (una vez por sesión y archivo: Map001.json.astra-bak).
const backed=new Set();
Astra.saveFile=async function(p,path,text){
 const key=p.name+"/"+path;
 if(!backed.has(key)&&await p.backend.exists(path)){await p.backend.write(path+".astra-bak",await p.backend.text(path));backed.add(key);}
 await p.backend.write(path,text);
};
Astra.image=async function(p,path){
 if(!path)return null;if(p.images[path]!==undefined)return p.images[path];
 p.images[path]=(async()=>{try{return await createImageBitmap(await p.backend.blob(path));}catch(e){return null;}})();
 return p.images[path];
};

// ASTRA map maintenance. Only remove map JSONs; preserve shared tilesets, art and database rows.
Astra.inspectProjectMaps=async function(p){
 const rows=[];
 for(const info of (p.mapInfos||[]).filter(Boolean)){
  const id=Number(info.id);Tactics.assert(Number.isInteger(id)&&id>0,"ID de mapa inválido");
  const path=Astra.mapPath(id),raw=await p.backend.text(path),map=JSON.parse(raw);
  rows.push({id,name:info.name,path,raw,map,imported:/<FE8Import:[^>]+>/.test(map.note||"")});
 }
 return rows;
};
Astra.purgeProjectMaps=async function(p,rows,ids,keepId){
 const remove=new Set(ids.map(Number)),live=rows.filter(m=>!remove.has(m.id)),gone=rows.filter(m=>remove.has(m.id));
 Tactics.assert(gone.length&&live.length&&gone.length===remove.size,"Conserva al menos un mapa y elige IDs válidos");
 const keep=live.find(m=>m.id===Number(keepId))||live[0];
 Tactics.assert(typeof p.backend.removeMap==="function","La limpieza solo está disponible en proyectos locales con permiso de escritura");
 const folder="astra_backups/mapas_"+new Date().toISOString().replace(/[:.]/g,"-")+"_"+Math.random().toString(36).slice(2,8);
 // Always preserve a complete recoverable snapshot before changing the project index.
 const paths=["data/MapInfos.json","data/System.json",...(p.packName&&p.pack?["data/"+p.packName+".json"]:[])];
 for(const path of paths)await p.backend.write(folder+"/"+path,await p.backend.text(path));
 for(const m of gone)await p.backend.write(folder+"/"+m.path,m.raw);
 const infos=Tactics.copy(p.mapInfos),system=Tactics.copy(p.system),pack=p.pack?Tactics.copy(p.pack):null;
 for(const m of gone){infos[m.id]=null;if(pack&&pack.maps)delete pack.maps[m.id];}
 for(const m of infos.filter(Boolean))if(remove.has(Number(m.parentId)))m.parentId=0;
 if(remove.has(Number(system.startMapId))||!live.some(m=>m.id===Number(system.startMapId))){system.startMapId=keep.id;system.startX=0;system.startY=0;}
 // Index is written last. If a metadata write fails, roll back from the snapshot.
 try{
  await Astra.saveFile(p,"data/System.json",JSON.stringify(system));
  if(pack&&p.packName)await Astra.saveFile(p,"data/"+p.packName+".json",JSON.stringify(pack));
  await Astra.saveFile(p,"data/MapInfos.json",JSON.stringify(infos));
 }catch(e){for(const path of paths){try{await p.backend.write(path,await p.backend.text(folder+"/"+path));}catch(ignored){}}throw new Error(e.message+". Respaldo: "+folder);}
 const failures=[];
 // Only remove files once they are no longer referenced by MapInfos. Do not remove shared graphics.
 for(const m of gone){try{await p.backend.removeMap(m.path);}catch(e){failures.push(m.path+": "+e.message);}}
 return {deleted:gone.length,remaining:live.length,keepId:keep.id,folder,failures};
};
