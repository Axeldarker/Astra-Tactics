// project.js: lectura y actualización de js/plugins.js (sin navegador).
const loadProjectJs=()=>{const window={Tactics:T};new Function("window",fs.readFileSync(path.join(__dirname,"..","src","app","project.js"),"utf8"))(window);return window.Astra;};
test("plugins.js: detecta la v0.2 y la actualiza a los 3 plugins conservando parámetros",()=>{
 const A=loadProjectJs();
 const old=["TacticsSystem","TacticsCommands","TacticsRules","TacticsView","TacticsGraphics","TacticsPresentation","TacticsScenes","TacticsData"].map(name=>({name,status:true,description:"",parameters:{}}));
 const text="// Generated by RPG Maker.\nvar $plugins =\n"+JSON.stringify([{name:"OtroPlugin",status:true,parameters:{}}].concat(old,[{name:"TacticsMZ",status:true,parameters:{ResourcePack:"TacticsGraphics"}}]),null,2)+";\n";
 const list=A.parsePlugins(text),st=A.pluginStatus(list);
 assert.equal(st.legacy,true);assert.equal(st.ok,false);assert.equal(st.old.length,8);
 const up=A.upgradePlugins(list);
 assert.deepEqual(up.map(p=>p.name),["OtroPlugin","TacticsEngine","TacticsUI","TacticsMZ"]);
 assert.equal(up[3].parameters.ResourcePack,"TacticsGraphics");assert.equal(up[3].parameters.EnemyPresets,"[]");
 assert.equal(A.pluginStatus(up).ok,true);
 assert.deepEqual(A.parsePlugins(A.writePlugins(up)),up,"lo que escribe se vuelve a leer igual");
});
test("plugins.js: proyecto sin TacticsMZ",()=>{
 const A=loadProjectJs(),up=A.upgradePlugins([]);
 assert.equal(A.pluginStatus([]).missing,true);assert.deepEqual(up.map(p=>p.name),["TacticsEngine","TacticsUI","TacticsMZ"]);
});
